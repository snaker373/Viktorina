// Відображення заголовка
void показатиЗаголовок() {
    встановитиКолір(ЯРКИЙ_БИРЮЗОВИЙ);
    cout << "╔════════════════════════════════════════════╗" << endl;
    cout << "║           🎯 ВІКТОРИНА 2024 🎯              ║" << endl;
    cout << "╚════════════════════════════════════════════╝" << endl;
    скинутиКолір();
    cout << endl;
}

// Відображення прогрес-бару
void показатиПрогресБар(int поточний, int всього) {
    int ширина = 40;
    int заповнено = (int)((double)поточний / всього * ширина);

    встановитиКолір(ЯРКИЙ_ЖОВТИЙ);
    cout << "[";
    for (int i = 0; i < ширина; i++) {
        if (i < заповнено) {
            встановитиКолір(ЯРКИЙ_ЗЕЛЕНИЙ);
            cout << "█";
        } else {
            встановитиКолір(СІРИЙ);
            cout << "░";
        }
    }
    встановитиКолір(ЯРКИЙ_ЖОВТИЙ);
    cout << "] " << поточний << "/" << всього;
    скинутиКолір();
    cout << endl << endl;
}

// Відображення питання
void показатиПитання(const Питання& п, int номерПитання, int всьогоПитань) {
    встановитиКолір(ЯРКИЙ_БІЛИЙ);
    cout << "📝 Питання " << номерПитання << " з " << всьогоПитань << ":" << endl;
    скинутиКолір();
    cout << endl;

    встановитиКолір(БІЛИЙ);
    cout << п.текст << endl;
    скинутиКолір();
    cout << endl;

    for (size_t i = 0; i < п.варіанти.size(); i++) {
        встановитиКолір(ЯРКИЙ_БИРЮЗОВИЙ);
        cout << "  " << (i + 1) << ". ";
        скинутиКолір();
        встановитиКолір(БІЛИЙ);
        cout << п.варіанти[i] << endl;
        скинутиКолір();
    }
    cout << endl;
}

// Відображення правильної відповіді
void показатиПравильнаВідповідь(const Питання& п) {
    встановитиКолір(ЯРКИЙ_ЗЕЛЕНИЙ);
    cout << "✓ Правильна відповідь: " << (п.правильнаВідповідь + 1) << ". " << п.варіанти[п.правильнаВідповідь] << endl;
    скинутиКолір();
}

// Відображення результату
void показатиРезультат(int бали, int всього) {
    очиститиЕкран();
    показатиЗаголовок();

    double відсоток = (double)бали / всього * 100;

    встановитиКолір(ЯРКИЙ_ЖОВТИЙ);
    cout << "╔════════════════════════════════════════════╗" << endl;
    cout << "║              📊 РЕЗУЛЬТАТ 📊               ║" << endl;
    cout << "╚════════════════════════════════════════════╝" << endl;
    скинутиКолір();
    cout << endl;

    встановитиКолір(БІЛИЙ);
    cout << "Правильних відповідей: ";
    встановитиКолір(ЯРКИЙ_ЗЕЛЕНИЙ);
    cout << бали << " з " << всього << endl;
    скинутиКолір();

    встановитиКолір(БІЛИЙ);
    cout << "Відсоток правильних: ";
    встановитиКолір(ЯРКИЙ_БИРЮЗОВИЙ);
    cout << відсоток << "%" << endl;
    скинутиКолір();
    cout << endl;

    // Оцінка
    if (відсоток == 100) {
        встановитиКолір(ЯРКИЙ_ЗЕЛЕНИЙ);
        cout << "🏆 ІДЕАЛЬНО! Ви справжній ерудит! 🏆" << endl;
    } else if (відсоток >= 80) {
        встановитиКолір(ЯРКИЙ_БИРЮЗОВИЙ);
        cout << "🌟 Чудовий результат! Так тримати! 🌟" << endl;
    } else if (відсоток >= 60) {
        встановитиКолір(ЯРКИЙ_ЖОВТИЙ);
        cout << "👍 Хороший результат! Є куди рости! 👍" << endl;
    } else if (відсоток >= 40) {
        встановитиКолір(ЯРКИЙ_ПУРПУРОВИЙ);
        cout << "📚 Непогано, але варто повчитися! 📚" << endl;
    } else {
        встановитиКолір(ЯРКИЙ_ЧЕРВОНИЙ);
        cout << "💪 Не здавайтеся! Спробуйте ще раз! 💪" << endl;
    }
    скинутиКолір();

    cout << endl;
    встановитиКолір(ЯРКИЙ_ЖОВТИЙ);
    cout << "╚════════════════════════════════════════════╝" << endl;
    скинутиКолір();
}

