// Встановлення кольору тексту
void встановитиКолір(Color колірТексту, Color колірФону = ЧОРНИЙ) {
    HANDLE hConsole = GetStdHandle(STD_OUTPUT_HANDLE);
    SetConsoleTextAttribute(hConsole, (WORD)((колірФону << 4) | колірТексту));
}

// Скид кольору
void скинутиКолір() {
    встановитиКолір(БІЛИЙ, ЧОРНИЙ);
}

