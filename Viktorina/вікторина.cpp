// Запуск вікторини
void запуститиВікторину() {
    vector<Питання> питання = завантажитиПитання();
    int бали = 0;
    int всьогоПитань = питання.size();

    for (size_t i = 0; i < питання.size(); i++) {
        очиститиЕкран();
        показатиЗаголовок();
        показатиПрогресБар(i + 1, всьогоПитань);
        показатиПитання(питання[i], i + 1, всьогоПитань);

        встановитиКолір(ЯРКИЙ_БИРЮЗОВИЙ);
        cout << "Ваша відповідь: ";
        скинутиКолір();

        int відповідьКористувача;
        cin >> відповідьКористувача;

        cout << endl;

        if (відповідьКористувача >= 1 && відповідьКористувача <= 4) {
            if (відповідьКористувача - 1 == питання[i].правильнаВідповідь) {
                встановитиКолір(ЯРКИЙ_ЗЕЛЕНИЙ);
                cout << "✓ Правильно!" << endl;
                скинутиКолір();
                бали++;
            } else {
                встановитиКолір(ЯРКИЙ_ЧЕРВОНИЙ);
                cout << "✗ Неправильно!" << endl;
                скинутиКолір();
                cout << endl;
                показатиПравильнаВідповідь(питання[i]);
            }
        } else {
            встановитиКолір(ЯРКИЙ_ЧЕРВОНИЙ);
            cout << "✗ Невірний ввід!" << endl;
            скинутиКолір();
            cout << endl;
            показатиПравильнаВідповідь(питання[i]);
        }

        чекатиНатискання();
    }

    показатиРезультат(бали, всьогоПитань);

    cout << endl;
    встановитиКолір(ЯРКИЙ_БИРЮЗОВИЙ);
    cout << "Хочете повернутися в головне меню? (y/n): ";
    скинутиКолір();

    char вибір;
    cin >> вибір;

    if (вибір == 'y' || вибір == 'Y' || вибір == 'т' || вибір == 'Т') {
        return;
    }
}

